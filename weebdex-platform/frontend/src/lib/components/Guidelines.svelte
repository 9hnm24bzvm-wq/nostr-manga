		<strong class="text-red-400">Do Not upload:</strong>
		<ul>
			<li>Western comics (e.g., Marvel, DC).</li>
			<li>Official publisher rips (e.g., MangaPlus, Kindle rips).</li>
			<li>
				Bulk collections (e.g., entire volume's worth of chapters as just "volume 1"). Upload chapters individually.
			</li>
			<li>Fully automated translations (e.g., using a website that translates and typesets for you).</li>
		</ul>
	</div>
	<div>
		<strong>File Technical Limits:</strong>
		<ul>
			<li>Allowed Formats: JPEG, PNG, GIF.</li>
			<li>Image Dimensions: Max 10,000 x 10,000 pixels.</li>
			<li>File Size: Max 25 MB per image; Max 500 MB per chapter.</li>
		</ul>
	</div>
	<div>
		<strong>Naming Conventions:</strong>
		<ul>
			<li>No Zero-Padding. Write Chapter "6", not Chapter "06".</li>
			<li>Decimals for Extras. Use decimals (e.g., 10.5) for omitted chapters, bonus content, or side stories.</li>
			<li>No chapter # in titles, unless that is actually the title of the chapter.</li>
			<li>
				Volume Numbers should only be present if a chapter is a part of a volume release. If the volume has not yet
				released, do not add a volume number. For webtoons and other forms of media where there are "seasons" instead of
				volumes, use the volume number to mark the season.
			</li>
		</ul>
	</div>
	<div>
		<strong>Preservation & Integrity Standards:</strong>
		<ul>
			<li>
				Do not remove credit pages, recruitment pages, watermarks, or any other aspects of the chapter. Upload the
				chapter exactly as it is (or was) being distributed by the original scanlation group.
				<ul>
					<li>exception to this are miscellaneous pages unrelated to the story in the middle of the chapter.</li>
					<li>
						exception to this are also pages and watermarks inserted by whoever is hosting the images that the original
						scanlation group did not add themselves (e.g. aggregator watermarks).
					</li>
				</ul>
			</li>
			<li>
				Do not apply any additional filters or compression techniques on the images beyond those already done by the
				group releasing the chapters. Use the highest quality available version of the chapter.
				<ul>
					<li>exception to this is when the original group is defunct and/or no higher-quality releases exist</li>
				</ul>
			</li>
		</ul>
	</div>
	<div>
		<strong>Metadata & Tagging Requirements:</strong>
		<ul>
			<li>
				Credit the Group. If the scanlation group is known, select them from the database. If the group does not yet
				exist, create a new entry for it.
				<ul>
					<li>if the group is not known, use the "Unknown" group.</li>
				</ul>
			</li>
			<li>
				Do not credit yourself if you did not work on the release.
				<ul>
					<li>
						exception to this is when there is no group to credit, or if you are working solo (meaning without a group)
					</li>
				</ul>
			</li>
		</ul>
